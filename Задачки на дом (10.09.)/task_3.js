// //3. Написать функцию проверки знания таблицы умножения. Программа должна вывести 10 примеров и выставить оценку: 
// за 10 правильных ответов - "отлично", 
// за 8 или 9 правильных ответов - "хорошо", 
// за 6 или 7 правильных ответов - "удовлетворительно", 
// остальные варианты - "плохо". 
// (Примеры должны генерироваться рандомно!). При решении задачи использовать цикл for. 

function multiplicationTest() {
    let correct = 0;

    for (let i = 1; i <= 10; i++) {
        let a = Math.floor(Math.random() * 9) + 2; // cлучайное число от 2 до 10
        let b = Math.floor(Math.random() * 9) + 2; // cлучайное число от 2 до 10

        let answer = Number(prompt(i + ") " + a + " * " + b + " =")); // запрашиваем ответ пользователя

        if (answer === a * b) { // проверяем правильность ответа
            console.log("Правильно!");
            correct++;          // увеличиваем счетчик правильных ответов
        } else {
            console.log("Неправильно. Правильный ответ:", a * b);
        }
    }

    console.log("Правильных ответов:", correct); // выводим количество правильных ответов

    if (correct === 10) {
        console.log("Оценка: отлично");
    } else if (correct >= 8) { // проверяем количество правильных ответов
        console.log("Оценка: хорошо");
    } else if (correct >= 6) { // проверяем количество правильных ответов
        console.log("Оценка: удовлетворительно");
    } else {                    // если правильных ответов меньше 6
        console.log("Оценка: плохо");
    }
}

multiplicationTest();

