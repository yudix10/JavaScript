let n = Number(prompt("Введите количество элементов:"));
let arr = [];

for (let i = 0; i < n; i++) {                           
    arr.push(Math.floor(Math.random() * 21) - 10);      // Заполняем массив случайными числами от -10 до 10
}

if (n < 2) {
    return "Недостаточно элементов";            // Если элементов меньше двух, возвращаем сообщение о недостаточности элементов
}

let d = arr[1] - arr[0];                    // Вычисляем разность между первым и вторым элементами массива, предполагая, что это разность арифметической прогрессии

let isProgression = true;                   // Предполагаем, что массив образует арифметическую прогрессию, пока не доказано обратное

for (let i = 2; i < arr.length; i++) {          // Начинаем проверку с третьего элемента массива (индекс 2)

    if (arr[i] - arr[i - 1] != d) {

        isProgression = false;                  // Если разность между текущим и предыдущим элементом не равна предполагаемой разности, устанавливаем флаг в false

        break;
    }
}

console.log("Массив:", arr);        // Выводим массив для наглядности

if (isProgression) {

    console.log("Разность прогрессии:", d);         // Выводим разность арифметической прогрессии, если массив образует прогрессию

    return d;

} else {

    console.log("Не образуют");                     // Выводим сообщение, если массив не образует арифметическую прогрессию

    return "Не образуют";
}
